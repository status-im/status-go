// Package cryptokitties provides Go bindings for the CryptoKitties smart contract.
//
// CryptoKitties is a non-standard ERC721 implementation that uses a custom
// transfer(address,uint256) method instead of the standard transferFrom method
// for token transfers. This package contains the generated Go bindings and
// contract addresses for different networks.
//
// The bindings were generated using abigen from the official CryptoKitties
// contract ABI.
package cryptokitties
